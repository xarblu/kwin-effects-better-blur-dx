# Regenerate the gettext translation template (po/kwin_better_blur_dx.pot).
#
# Can be run both standalone and inside KDE's scripty environment
# (where $XGETTEXT, $EXTRACTRC and $podir are predefined).
#
# Usage:
#   sh Messages.sh            # writes po/kwin_better_blur_dx.pot
#   podir=/tmp sh Messages.sh # writes the template to /tmp instead

set -e

ROOTDIR=$(cd "$(dirname "$0")" && pwd)
cd "$ROOTDIR"

podir=${podir:-po}
XGETTEXT=${XGETTEXT:-xgettext}
EXTRACTRC=${EXTRACTRC:-extractrc}
DOMAIN=kwin_better_blur_dx

mkdir -p "$podir"
TMPDIR=$(mktemp -d)
trap 'rm -rf "$TMPDIR"' EXIT INT TERM

# 1. Translatable strings from Qt Designer .ui and KConfigXT .kcfg files.
#    Use KDE's extractrc when available, otherwise fall back to a small
#    built-in extractor so the script works without the full KDE SDK.
if command -v "$EXTRACTRC" >/dev/null 2>&1; then
    "$EXTRACTRC" src/kcm/blur_config.ui src/blur.kcfg > "$TMPDIR/rc.cpp"
else
    python3 - "$TMPDIR/rc.cpp" <<'PY'
import re
import sys
import xml.etree.ElementTree as ET

out = sys.argv[1]
lines = []
for path in ("src/kcm/blur_config.ui", "src/blur.kcfg"):
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError):
        continue
    # Every <string>...</string> inside a .ui file is user visible.
    for elem in root.iter():
        if elem.tag == "string" and elem.text:
            text = elem.text.replace("\\", "\\\\").replace('"', '\\"')
            text = text.replace("\n", "\\n")
            lines.append(f'i18n("{text}");')

with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
PY
fi

# 2. Translatable KPlugin metadata (Name/Description) from metadata.json.
python3 - "$TMPDIR/json.cpp" <<'PY'
import json
import sys

with open("src/metadata.json", encoding="utf-8") as f:
    data = json.load(f)

plugin = data.get("KPlugin", {})
lines = []
for key in ("Name", "Description"):
    value = plugin.get(key)
    if value:
        value = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'i18n("{value}");')

with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
PY

# 3. C++ sources (i18n()/i18nc()/i18np() calls and tr2i18n() generated by uic).
"$XGETTEXT" \
    --language=C++ \
    --from-code=UTF-8 \
    --package-name="$DOMAIN" \
    --package-version="2.5.1" \
    --msgid-bugs-address="https://github.com/xarblu/kwin-effects-better-blur-dx/issues" \
    -ki18n -ki18nc:1c,2 -ki18np:1,2 -ki18ncp:1c,2 \
    -ki18nd:2 -ki18ndc:2c,3 -ki18ndp:2,3 -ki18ndcp:2c,3,4 \
    -ktr2i18n:1 -ktr2xi18n:1 \
    --flag=i18n:1:no-c-format --flag=i18nc:2:no-c-format \
    --flag=i18np:1:no-c-format --flag=i18np:2:no-c-format \
    --flag=tr2i18n:1:no-c-format \
    -o "$podir/$DOMAIN.pot" \
    src/kcm/blur_config.cpp \
    "$TMPDIR/rc.cpp" \
    "$TMPDIR/json.cpp"

# Normalize the POT-Creation-Date so regenerated templates stay diff-friendly.
sed -i 's/^"POT-Creation-Date: .*/"POT-Creation-Date: 2026-01-01 00:00+0000\\n"/' "$podir/$DOMAIN.pot"

echo "Generated $podir/$DOMAIN.pot"
